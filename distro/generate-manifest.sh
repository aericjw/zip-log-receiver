#!/usr/bin/env bash
# Generate builder.yaml: Bindplane's BDOT component set (so every Bindplane source/destination is
# compatible) + zip_log, minus what a third-party build cannot use (repo-internal modules, forked replaces).
# Usage: ./generate-manifest.sh [--ci] [BDOT_VERSION] [RECEIVER_DIR]   e.g. ./generate-manifest.sh v1.109.0
#   default: writes distro/builder.yaml, receiver referenced by absolute path (local builds)
#   --ci:    writes ../manifest.yaml at the repo root, receiver referenced as ../ziplogreceiver (GitHub Action)
set -euo pipefail
CI_MODE=false
if [ "${1:-}" = "--ci" ]; then CI_MODE=true; shift; fi
VERSION="${1:-v1.109.0}"
RECEIVER_DIR="$(cd "${2:-$(dirname "$0")/../ziplogreceiver}" && pwd)"   # absolute: ocb resolves replaces from build/
[ -f "$RECEIVER_DIR/go.mod" ] || { echo "no go.mod in $RECEIVER_DIR" >&2; exit 1; }
SRC="https://raw.githubusercontent.com/observIQ/bindplane-otel-collector/${VERSION}/manifests/observIQ/manifest.yaml"
if $CI_MODE; then OUT="$(dirname "$0")/../manifest.yaml"; else OUT="$(dirname "$0")/builder.yaml"; fi

curl -fsSL "$SRC" | python3 -I -c '
import sys,re
receiver_dir=sys.argv[1]; version=sys.argv[2]
mod="github.com/aericjw/zip-log-receiver/ziplogreceiver"
lines=sys.stdin.read().splitlines()
out=["# GENERATED by generate-manifest.sh from BDOT "+version+" - do not edit by hand.",
"dist:","  name: zip-log-collector","  description: BDOT component set plus the zip_log receiver","  module: github.com/aericjw/zip-log-receiver/distro",
"  version: 0.1.0","  output_path: ./build","","conf_resolver:","  default_uri_scheme: \"env\"",""]
skip_section=False
for l in lines:
    if re.match(r"^(dist|conf_resolver):",l): skip_section=True; continue
    if re.match(r"^replaces:",l): break
    if re.match(r"^[a-z_]+:",l):
        skip_section=False; out.append(l)
        if l.startswith("receivers:"): out.append(f"  - gomod: {mod} v0.0.0")
        continue
    if skip_section or l.strip().startswith("#") or not l.strip(): 
        if not skip_section and not l.strip(): out.append("")
        continue
    if "/internal/" in l or "jmxreceiver" in l: continue   # internal modules / receiver removed upstream
    if l.startswith("    ") and not l.strip().startswith("- gomod"): continue
    out.append(l)
txt="\n".join(out)
# Bindplane components that BDOT keeps internal but bindplane-otel-contrib publishes
if "extension/bindplaneextension" not in txt:
    txt=txt.replace("\nextensions:\n","\nextensions:\n  - gomod: github.com/observiq/bindplane-otel-contrib/extension/bindplaneextension v1.15.0\n",1)
if "processor/snapshotprocessor" not in txt:
    txt=txt.replace("\nprocessors:\n","\nprocessors:\n  - gomod: github.com/observiq/bindplane-otel-contrib/processor/snapshotprocessor v1.15.0\n",1)
txt=txt.rstrip("\n")+f"\n\nreplaces:\n  - {mod} => {receiver_dir}\n"
print(txt)
' "$($CI_MODE && echo ../ziplogreceiver || echo "$RECEIVER_DIR")" "$VERSION" > "$OUT"
echo "wrote $OUT: $(grep -c 'gomod:' "$OUT") components"
